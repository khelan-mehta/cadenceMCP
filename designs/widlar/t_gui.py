from vgui import run_gui
il = r'''
printf("SKILL_START\n")
foreach(c '("nmos2v" "resnsppoly")
  cdf = cdfGetBaseCellCDF(ddGetObj("gpdk090" c))
  printf("MCP:%s_spectre=%L\n" c cdf~>simInfo~>spectre)
  printf("MCP:%s_auCdl=%L\n" c cdf~>simInfo~>auCdl))
unless( ddGetObj("widlar_lib") dbCreateLib("widlar_lib" "/home/work/widlar_lib"))
r1 = errset(techBindTechFile(ddGetObj("widlar_lib") "gpdk090") t)
printf("MCP:bind=%L\n" r1)
cv = dbOpenCellViewByType("widlar_lib" "probe_lay" "layout" "maskLayout" "w")
i1 = dbCreateParamInstByMasterName(cv "gpdk090" "nmos2v" "layout" "M1" 0:0 "R0" 1 list(list("fw" "float" 1.56e-6) list("l" "float" 2.8e-7) list("connectGates" "string" "Top")))
i2 = dbCreateParamInstByMasterName(cv "gpdk090" "resnsppoly" "layout" "R1" 5:0 "R0" 1 list(list("segW" "float" 1e-6) list("segL" "float" 10e-6) list("segments" "int" 4)))
foreach(i list(i1 i2)
  foreach(t i~>master~>terminals printf("MCP:term %s %s %L\n" i~>name t~>name mapcar(lambda((p) list(p~>fig~>layerName p~>fig~>bBox)) t~>pins))))
printf("MCP:bbox1=%L bbox2=%L\n" i1~>bBox i2~>bBox)
dbSave(cv)
w = geOpen(?lib "widlar_lib" ?cell "probe_lay" ?view "layout" ?mode "r")
printf("MCP:win=%L\n" w)
hiResizeWindow(hiGetCurrentWindow() list(0:0 1600:1000))
hiZoomAbsoluteScale(hiGetCurrentWindow() 0.9)
leHiZoomToFit = errset(hiZoomToFit(hiGetCurrentWindow()) t)
procedure(step1() mcpShot("probe_layout") hiRegTimer("step2()" 10))
procedure(step2() printf("MCP:OK=1\n") exit(0))
hiRegTimer("step1()" 50)
'''
log, got, _ = run_gui(il, shots=["probe_layout"], timeout=600)
open("designs/widlar/t_gui.log","w",encoding="utf-8").write(log)
