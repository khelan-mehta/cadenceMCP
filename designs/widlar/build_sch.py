import sys, re; sys.path.insert(0, "designs/widlar")
from vgui import run_gui

SEGS, SEGL = 28, 24.195          # 400 ohm/sq * 1u wide * 28*24.195u = 271.0 k
RTOT = 400 * SEGS * SEGL / 1.0   # ohms
EFFL = SEGS * SEGL

il = r'''
printf("SKILL_START\n")
lib = "widlar_lib"
; pin hotspot of a master terminal, transformed into the parent cellview
procedure( pinPt(inst tn)
  let( (mt fig)
    mt = car(setof(x inst~>master~>terminals x~>name==tn))
    fig = car(mt~>pins)~>fig
    dbTransformPoint(centerBox(fig~>bBox) inst~>transform)))
procedure( W(cv pts) schCreateWire(cv "route" "full" pts 0.0 0.0 0.0))
nm  = dbOpenCellViewByType("gpdk090" "nmos2v" "symbol" nil "r")
rpm = dbOpenCellViewByType("gpdk090" "resnsppoly" "symbol" nil "r")
iop = dbOpenCellViewByType("basic" "iopin" "symbol" nil "r")
printf("MCP:masters=%L\n" list(nm!=nil rpm!=nil iop!=nil))
foreach(c '("nmos2v" "resnsppoly")
  cdf = cdfGetBaseCellCDF(ddGetObj("gpdk090" c))
  printf("MCP:siminfo_%s=%L\n" c cdf~>simInfo~>spectre))

; ================= core schematic =================
cv = dbOpenCellViewByType(lib "widlar_core" "schematic" "schematic" "w")
mosP = list(list("model" "string" "gpdk090_nmos2v") list("w" "string" "@WW@") list("fw" "string" "@FW@")
            list("l" "string" "@LL@") list("fingers" "string" "@FG@") list("m" "string" "1"))
M1 = dbCreateParamInst(cv nm "M1" 0:0 "MY" 1 mosP)
M2 = dbCreateParamInst(cv nm "M2" 3.0:0 "R0" 1 mosP)
rsP = list(list("model" "string" "gpdk090_resnsppoly") list("segments" "int" @SEGS@) list("ssegs" "int" @SEGS@)
           list("psegs" "int" 1) list("segW" "string" "@SEGW@") list("segL" "string" "@SEGL@")
           list("r" "string" "@RVAL@") list("segR" "string" "@SEGR@")
           list("effW" "string" "@SEGW@") list("effL" "string" "@EFFL@")
           list("w" "string" "@SEGW@") list("l" "string" "@EFFL@"))
RS = dbCreateParamInst(cv rpm "RS" 0:0 "R0" 1 rsP)
pS = pinPt(M2 "S")
pP = pinPt(RS "PLUS")
RS~>xy = list(xCoord(pS)-xCoord(pP) yCoord(pS)-yCoord(pP)-1.0)
foreach(i list(M1 M2 RS) foreach(tn i~>master~>terminals~>name printf("MCP:pin %s.%s=%L\n" i~>name tn pinPt(i tn))))
g1 = pinPt(M1 "G") g2 = pinPt(M2 "G") d1 = pinPt(M1 "D") d2 = pinPt(M2 "D")
s1 = pinPt(M1 "S") s2 = pinPt(M2 "S") b1 = pinPt(M1 "B") b2 = pinPt(M2 "B")
rp = pinPt(RS "PLUS") rm = pinPt(RS "MINUS") rb = pinPt(RS "B")
yP = yCoord(d1)+0.75  yTop = yP+0.75  yG = yCoord(rm)-0.75
xm = (xCoord(g1)+xCoord(g2))/2.0
W(cv list(g1 xm:yCoord(g1)))
W(cv list(xm:yCoord(g1) g2))
W(cv list(d1 xCoord(d1):yP))
W(cv list(xCoord(d1):yP xm:yP))
W(cv list(xm:yP xm:yCoord(g1)))
W(cv list(d1 xCoord(d1):yTop))
W(cv list(d2 xCoord(d2):yTop))
schCreatePin(cv iop "IREF" "inputOutput" nil xCoord(d1):yTop "R90")
schCreatePin(cv iop "IOUT" "inputOutput" nil xCoord(d2):yTop "R90")
wns = car(W(cv list(s2 rp)))
schCreateWireLabel(cv wns xCoord(s2)+0.1:(yCoord(s2)+yCoord(rp))/2.0 "NS" "lowerLeft" "R0" "stick" 0.0625 nil)
xL = xCoord(s1)-1.0  xR = xCoord(rb)+1.0
W(cv list(rm xCoord(rm):yG))
W(cv list(s1 xCoord(s1):yG))
W(cv list(b1 xCoord(b1)-0.5:yCoord(b1)))
W(cv list(xCoord(b1)-0.5:yCoord(b1) xCoord(b1)-0.5:yG))
W(cv list(b2 xCoord(b2)+0.5:yCoord(b2)))
W(cv list(xCoord(b2)+0.5:yCoord(b2) xCoord(b2)+0.5:yG))
W(cv list(rb xR:yCoord(rb)))
W(cv list(xR:yCoord(rb) xR:yG))
W(cv list(xL:yG xR:yG))
schCreatePin(cv iop "GND" "inputOutput" nil xL:yG "R180")
chk = schCheck(cv)
printf("MCP:schcheck=%L\n" chk)
dbSave(cv)
printf("MCP:core_nets=%L\n" cv~>nets~>name)
foreach(i list(M1 M2 RS)
  foreach(it i~>instTerms printf("MCP:conn %s.%s=%s\n" i~>name it~>name it~>net~>name)))

; ================= symbol =================
s1r = errset(schViewToView("widlar_lib" "widlar_core" "widlar_lib" "widlar_core" "schematic" "symbol" "schSchemToPinList" "schPinListToSymbol") t)
printf("MCP:symgen1=%L\n" s1r)
unless( ddGetObj("widlar_lib" "widlar_core" "symbol")
  s2r = errset(schViewToView("widlar_lib" "widlar_core" "schematic" "widlar_lib" "widlar_core" "symbol" "schSchemToPinList" "schPinListToSymbol") t)
  printf("MCP:symgen2=%L\n" s2r))
printf("MCP:symexists=%L\n" ddGetObj("widlar_lib" "widlar_core" "symbol")!=nil)

; ================= testbench =================
sym = dbOpenCellViewByType(lib "widlar_core" "symbol" nil "r")
when( sym
  tb = dbOpenCellViewByType(lib "widlar_tb" "schematic" "schematic" "w")
  X = dbCreateInst(tb sym "I0" 0:0 "R0" 1)
  vdcM = dbOpenCellViewByType("analogLib" "vdc" "symbol" nil "r")
  idcM = dbOpenCellViewByType("analogLib" "idc" "symbol" nil "r")
  resM = dbOpenCellViewByType("analogLib" "res" "symbol" nil "r")
  gndM = dbOpenCellViewByType("analogLib" "gnd" "symbol" nil "r")
  pI = pinPt(X "IREF") pO = pinPt(X "IOUT") pG = pinPt(X "GND")
  printf("MCP:tbpins=%L\n" list(pI pO pG))
  V0 = dbCreateParamInst(tb vdcM "V0" list(xCoord(pI)-4.0 yCoord(pI)) "R0" 1 list(list("vdc" "string" "VDD")))
  I1 = dbCreateParamInst(tb idcM "IREF" list(xCoord(pI)-1.75 yCoord(pI)+2.0) "R0" 1 list(list("idc" "string" "Iref")))
  RL = dbCreateParamInst(tb resM "RL" list(xCoord(pO)+1.75 yCoord(pO)+2.0) "R0" 1 list(list("r" "string" "1M")))
  vp = pinPt(V0 "PLUS") vm = pinPt(V0 "MINUS")
  ip = pinPt(I1 "PLUS") im = pinPt(I1 "MINUS")
  lp = pinPt(RL "PLUS") lm = pinPt(RL "MINUS")
  yV = max(yCoord(vp) max(yCoord(ip) yCoord(lp)))+0.75
  W(tb list(vp xCoord(vp):yV))
  W(tb list(xCoord(vp):yV xCoord(lp):yV))
  W(tb list(ip xCoord(ip):yV))
  W(tb list(lp xCoord(lp):yV))
  W(tb list(im xCoord(im):yCoord(pI)))
  W(tb list(xCoord(im):yCoord(pI) pI))
  W(tb list(lm xCoord(lm):yCoord(pO)))
  W(tb list(xCoord(lm):yCoord(pO) pO))
  yGG = min(yCoord(vm) yCoord(pG))-1.0
  W(tb list(vm xCoord(vm):yGG))
  W(tb list(pG xCoord(pG):yGG))
  W(tb list(xCoord(vm):yGG xCoord(pG):yGG))
  G0 = dbCreateInst(tb gndM "G0" 0:0 "R0" 1)
  gpt = pinPt(G0 "gnd!")
  G0~>xy = list(xCoord(G0~>xy)+xCoord(pG)-xCoord(gpt) yCoord(G0~>xy)+yGG-yCoord(gpt))
  wv = car(setof(w tb~>shapes w~>objType=="line" && member(xCoord(ip):yV w~>points)))
  when(wv schCreateWireLabel(tb wv xCoord(ip):yV "vdd" "lowerLeft" "R0" "stick" 0.0625 nil))
  wi = car(setof(w tb~>shapes w~>objType=="line" && member(pI w~>points)))
  when(wi schCreateWireLabel(tb wi pI "iref" "lowerRight" "R0" "stick" 0.0625 nil))
  wo = car(setof(w tb~>shapes w~>objType=="line" && member(pO w~>points)))
  when(wo schCreateWireLabel(tb wo pO "iout" "lowerLeft" "R0" "stick" 0.0625 nil))
  printf("MCP:tbcheck=%L\n" schCheck(tb))
  dbSave(tb)
  printf("MCP:tb_nets=%L\n" tb~>nets~>name)
  foreach(it X~>instTerms printf("MCP:tbconn I0.%s=%s\n" it~>name it~>net~>name))
)

; ================= screenshots =================
w1 = geOpen(?lib lib ?cell "widlar_core" ?view "schematic" ?mode "r")
hiResizeWindow(hiGetCurrentWindow() list(0:0 1600:1000))
procedure(wlA() errset(hiZoomAbsoluteScale(hiGetCurrentWindow() 0.95)) errset(evalstring(hiGetBindKey("Schematics" "<Key>f")) t) hiRegTimer("wlB()" 30))
procedure(wlB() mcpShot("sch_core")
  when( ddGetObj("widlar_lib" "widlar_core" "symbol")
    geOpen(?lib lib ?cell "widlar_core" ?view "symbol" ?mode "r")
    hiResizeWindow(hiGetCurrentWindow() list(0:0 1600:1000)))
  hiRegTimer("wlC()" 30))
procedure(wlC() errset(evalstring(hiGetBindKey("Symbol" "<Key>f")) t) hiRegTimer("wlD()" 30))
procedure(wlD() mcpShot("sym_core")
  when( ddGetObj("widlar_lib" "widlar_tb" "schematic")
    geOpen(?lib lib ?cell "widlar_tb" ?view "schematic" ?mode "r")
    hiResizeWindow(hiGetCurrentWindow() list(0:0 1600:1000)))
  hiRegTimer("wlE()" 30))
procedure(wlE() errset(evalstring(hiGetBindKey("Schematics" "<Key>f")) t) hiRegTimer("wlF()" 30))
procedure(wlF() mcpShot("sch_tb") printf("MCP:OK=1\n") exit(0))
hiRegTimer("wlA()" 40)
'''
rep = {"@WW@": "3.12u", "@FW@": "1.56u", "@LL@": "280n", "@FG@": "2", "@SEGS@": str(SEGS),
       "@SEGW@": "1u", "@SEGL@": f"{SEGL}u", "@RVAL@": f"{RTOT:.6g}", "@SEGR@": f"{RTOT/SEGS:.6g}",
       "@EFFL@": f"{EFFL:.4f}u"}
for k, v in rep.items():
    il = il.replace(k, v)
log, got, _ = run_gui(il, shots=["sch_core", "sym_core", "sch_tb"], timeout=800, tag="sch")
open("designs/widlar/build_sch.log", "w", encoding="utf-8").write(log)
print(got)
print("\n".join(re.findall(r".*MCP:.*|.*\*Error\*.*", log))[:9000])
