"""Flat high-swing cascode mirror schematic arranged like the reference image:
V1+vdd/gnd far left | bias branch (I0 over diode M0) | input branch (I1 over
M3 over M1) | output branch (M4 over M2) | V2 sine source right.
Also builds hsc_core (M0..M4 + IBIAS/IIN/IOUT/GND pins) for LVS."""
import sys, re; sys.path.insert(0, "designs/widlar")
from vgui import run_gui

il = r'''
printf("SKILL_START\n")
lib = "widlar_lib"
procedure( pinPt(inst tn)
  let( (mt fig)
    mt = car(setof(x inst~>master~>terminals x~>name==tn))
    fig = car(mt~>pins)~>fig
    dbTransformPoint(centerBox(fig~>bBox) inst~>transform)))
procedure( W(cv pts) schCreateWire(cv "route" "full" pts 0.0 0.0 0.0))
procedure( placeAt(cv master name tn pt orient props)
  let( (i p)
    i = dbCreateParamInst(cv master name 0:0 orient 1 props)
    p = pinPt(i tn)
    i~>xy = list(xCoord(pt)-xCoord(p) yCoord(pt)-yCoord(p))
    i))
procedure( LBL(cv wirePt name)
  let((ww)
    ww = car(setof(w cv~>shapes w~>objType=="line" && member(wirePt w~>points)))
    when(ww schCreateWireLabel(cv ww wirePt name "lowerLeft" "R0" "stick" 0.0625 nil))))
nm   = dbOpenCellViewByType("gpdk090" "nmos2v" "symbol" nil "r")
vdcM = dbOpenCellViewByType("analogLib" "vdc" "symbol" nil "r")
vsinM= dbOpenCellViewByType("analogLib" "vsin" "symbol" nil "r")
idcM = dbOpenCellViewByType("analogLib" "idc" "symbol" nil "r")
gndM = dbOpenCellViewByType("analogLib" "gnd" "symbol" nil "r")
vddM = dbOpenCellViewByType("analogLib" "vdd" "symbol" nil "r")
iop  = dbOpenCellViewByType("basic" "iopin" "symbol" nil "r")
mosW = list(list("model" "string" "gpdk090_nmos2v") list("w" "string" "12u") list("fw" "string" "12u")
            list("l" "string" "1u") list("fingers" "string" "1") list("m" "string" "1"))
mosB = list(list("model" "string" "gpdk090_nmos2v") list("w" "string" "3u") list("fw" "string" "3u")
            list("l" "string" "1u") list("fingers" "string" "1") list("m" "string" "1"))

; ================= flat testbench =================
cv = dbOpenCellViewByType(lib "hsc" "schematic" "schematic" "w")
M0 = dbCreateParamInst(cv nm "M0" -5.0:0 "R0" 1 mosB)
M1 = dbCreateParamInst(cv nm "M1" 0:0 "R0" 1 mosW)
M3 = dbCreateParamInst(cv nm "M3" 0:1.5 "R0" 1 mosW)
M2 = dbCreateParamInst(cv nm "M2" 5.0:0 "R0" 1 mosW)
M4 = dbCreateParamInst(cv nm "M4" 5.0:1.5 "R0" 1 mosW)
g0=pinPt(M0 "G") d0=pinPt(M0 "D") s0=pinPt(M0 "S") b0=pinPt(M0 "B")
g1=pinPt(M1 "G") d1=pinPt(M1 "D") s1=pinPt(M1 "S") b1=pinPt(M1 "B")
g2=pinPt(M2 "G") d2=pinPt(M2 "D") s2=pinPt(M2 "S") b2=pinPt(M2 "B")
g3=pinPt(M3 "G") d3=pinPt(M3 "D") s3=pinPt(M3 "S") b3=pinPt(M3 "B")
g4=pinPt(M4 "G") d4=pinPt(M4 "D") s4=pinPt(M4 "S") b4=pinPt(M4 "B")
I0 = placeAt(cv idcM "I0" "MINUS" list(xCoord(d0) 2.8) "R0" list(list("idc" "string" "100u")))
I1 = placeAt(cv idcM "I1" "MINUS" list(xCoord(d3) 2.8) "R0" list(list("idc" "string" "100u")))
V1 = placeAt(cv vdcM "V1" "PLUS" list(-8.5 1.5) "R0" list(list("vdc" "string" "1.8")))
V2 = placeAt(cv vsinM "V2" "PLUS" list(8.5 2.1) "R0"
      list(list("vdc" "string" "900m") list("va" "string" "100m") list("freq" "string" "1K") list("acm" "string" "1")))
; vdd symbols above V1.PLUS, I0.PLUS, I1.PLUS
VD1 = placeAt(cv vddM "VDD1" "vdd!" list(-8.5 2.2) "R0" nil)
VD2 = placeAt(cv vddM "VDD2" "vdd!" list(xCoord(pinPt(I0 "PLUS")) 4.4) "R0" nil)
VD3 = placeAt(cv vddM "VDD3" "vdd!" list(xCoord(pinPt(I1 "PLUS")) 4.4) "R0" nil)
W(cv list(pinPt(V1 "PLUS") -8.5:2.2))
W(cv list(pinPt(I0 "PLUS") xCoord(pinPt(I0 "PLUS")):4.4))
W(cv list(pinPt(I1 "PLUS") xCoord(pinPt(I1 "PLUS")):4.4))
; bias branch: I0 -> M0 drain, diode tie, vb bus to M3/M4 gates
W(cv list(d0 xCoord(d0):yCoord(pinPt(I0 "MINUS"))))
W(cv list(g0 -5.5:0)) W(cv list(-5.5:0 -5.5:0.6)) W(cv list(-5.5:0.6 xCoord(d0):0.6))
W(cv list(xCoord(d0):2.2 -0.6:2.2)) W(cv list(-0.6:2.2 -0.6:4.1)) ; placeholder removed below
; (vb bus along y=2.2 with drops at the cascode gates)
W(cv list(-0.6:2.2 xCoord(g3):2.2))
W(cv list(xCoord(g3):2.2 g3))
W(cv list(xCoord(g3):2.2 xCoord(g4):2.2))
W(cv list(xCoord(g4):2.2 g4))
; input branch: I1 -> M3.D ; M3.S -> M1.D ; wide-swing tie nin -> M1.G/M2.G
W(cv list(pinPt(I1 "MINUS") d3))
W(cv list(s3 d1))
W(cv list(xCoord(d3):2.5 -1.4:2.5))
W(cv list(-1.4:2.5 -1.4:0))
W(cv list(-1.4:0 g1))
W(cv list(-1.4:0 -1.4:-0.9))
W(cv list(-1.4:-0.9 4.4:-0.9))
W(cv list(4.4:-0.9 4.4:0))
W(cv list(4.4:0 g2))
; output branch: M2.D -> M4.S ; M4.D -> V2
W(cv list(d2 s4))
W(cv list(d4 xCoord(d4):3.6))
W(cv list(xCoord(d4):3.6 8.5:3.6))
W(cv list(8.5:3.6 pinPt(V2 "PLUS")))
; grounds per branch
procedure( gndRail(cv xs gx)
  let( (yR)
    yR = -1.5
    foreach(x xs W(cv list(car(x):cadr(x) car(x):yR)))
    W(cv list(car(car(xs)):yR car(car(last(xs))):yR))
    placeAt(cv gndM strcat("G" sprintf(nil "%d" round(gx*10))) "gnd!" list(gx yR) "R0" nil)))
; M0 branch: S down, B right stub then down
W(cv list(b0 -4.25:0))
gndRail(cv list(list(xCoord(s0) yCoord(s0)) list(-4.25 0.0)) -4.5)
; input branch: M1.S ; M1.B stub; M3.B stub
W(cv list(b1 0.75:0))
W(cv list(b3 0.9:yCoord(b3))) W(cv list(0.9:yCoord(b3) 0.9:-0.3))
gndRail(cv list(list(xCoord(s1) yCoord(s1)) list(0.75 0.0) list(0.9 -0.3)) 0.5)
; output branch: M2.S ; M2.B ; M4.B
W(cv list(b2 5.75:0))
W(cv list(b4 5.9:yCoord(b4))) W(cv list(5.9:yCoord(b4) 5.9:-0.3))
gndRail(cv list(list(xCoord(s2) yCoord(s2)) list(5.75 0.0) list(5.9 -0.3)) 5.5)
; V1 and V2 grounds
W(cv list(pinPt(V1 "MINUS") -8.5:-1.5))
placeAt(cv gndM "GV1" "gnd!" list(-8.5 -1.5) "R0" nil)
W(cv list(pinPt(V2 "MINUS") 8.5:-0.5))
placeAt(cv gndM "GV2" "gnd!" list(8.5 -0.5) "R0" nil)
; labels
LBL(cv xCoord(g3):2.2 "vb")
LBL(cv -1.4:1.0 "nin")
LBL(cv xCoord(s3):0.8 "na")
LBL(cv xCoord(s4):0.8 "nb")
LBL(cv 7.0:3.6 "nout")
chk = schCheck(cv)
printf("MCP:flatcheck=%L\n" chk)
dbSave(cv)
foreach(i list(M0 M1 M2 M3 M4 I0 I1 V1 V2)
  foreach(it i~>instTerms printf("MCP:conn %s.%s=%s\n" i~>name it~>name it~>net~>name)))

; ================= LVS core =================
core = dbOpenCellViewByType(lib "hsc_core" "schematic" "schematic" "w")
C0 = dbCreateParamInst(core nm "M0" -5.0:0 "R0" 1 mosB)
C1 = dbCreateParamInst(core nm "M1" 0:0 "R0" 1 mosW)
C3 = dbCreateParamInst(core nm "M3" 0:1.5 "R0" 1 mosW)
C2 = dbCreateParamInst(core nm "M2" 5.0:0 "R0" 1 mosW)
C4 = dbCreateParamInst(core nm "M4" 5.0:1.5 "R0" 1 mosW)
cg0=pinPt(C0 "G") cd0=pinPt(C0 "D") cs0=pinPt(C0 "S") cb0=pinPt(C0 "B")
cg1=pinPt(C1 "G") cd1=pinPt(C1 "D") cs1=pinPt(C1 "S") cb1=pinPt(C1 "B")
cg2=pinPt(C2 "G") cd2=pinPt(C2 "D") cs2=pinPt(C2 "S") cb2=pinPt(C2 "B")
cg3=pinPt(C3 "G") cd3=pinPt(C3 "D") cs3=pinPt(C3 "S") cb3=pinPt(C3 "B")
cg4=pinPt(C4 "G") cd4=pinPt(C4 "D") cs4=pinPt(C4 "S") cb4=pinPt(C4 "B")
W(core list(cd0 xCoord(cd0):2.8))
schCreatePin(core iop "IBIAS" "inputOutput" nil xCoord(cd0):2.8 "R90")
W(core list(cg0 -5.5:0)) W(core list(-5.5:0 -5.5:0.6)) W(core list(-5.5:0.6 xCoord(cd0):0.6))
W(core list(xCoord(cd0):2.2 xCoord(cg3):2.2))
W(core list(xCoord(cg3):2.2 cg3))
W(core list(xCoord(cg3):2.2 xCoord(cg4):2.2))
W(core list(xCoord(cg4):2.2 cg4))
W(core list(cd3 xCoord(cd3):2.8))
schCreatePin(core iop "IIN" "inputOutput" nil xCoord(cd3):2.8 "R90")
W(core list(cs3 cd1))
W(core list(xCoord(cd3):2.5 -1.4:2.5))
W(core list(-1.4:2.5 -1.4:0))
W(core list(-1.4:0 cg1))
W(core list(-1.4:0 -1.4:-0.9))
W(core list(-1.4:-0.9 4.4:-0.9))
W(core list(4.4:-0.9 4.4:0))
W(core list(4.4:0 cg2))
W(core list(cd2 cs4))
W(core list(cd4 xCoord(cd4):2.8))
schCreatePin(core iop "IOUT" "inputOutput" nil xCoord(cd4):2.8 "R90")
; one common ground rail with pin
yR = -1.5
foreach(p list(cs0 cs1 cs2) W(core list(p xCoord(p):yR)))
W(core list(cb0 -4.25:0)) W(core list(-4.25:0 -4.25:yR))
W(core list(cb1 0.75:0)) W(core list(0.75:0 0.75:yR))
W(core list(cb2 5.75:0)) W(core list(5.75:0 5.75:yR))
W(core list(cb3 0.9:yCoord(cb3))) W(core list(0.9:yCoord(cb3) 0.9:yR))
W(core list(cb4 5.9:yCoord(cb4))) W(core list(5.9:yCoord(cb4) 5.9:yR))
W(core list(-6.3:yR 5.9:yR))
schCreatePin(core iop "GND" "inputOutput" nil -6.3:yR "R180")
printf("MCP:corecheck=%L\n" schCheck(core))
dbSave(core)
foreach(i list(C0 C1 C2 C3 C4)
  foreach(it i~>instTerms printf("MCP:cconn %s.%s=%s\n" i~>name it~>name it~>net~>name)))

; ================= screenshot =================
w1 = geOpen(?lib lib ?cell "hsc" ?view "schematic" ?mode "r")
hiSetCurrentWindow(w1)
hiResizeWindow(w1 list(0:0 1600:1000))
procedure(wlA() errset(evalstring(hiGetBindKey("Schematics" "<Key>f")) t) hiRegTimer("wlB()" 30))
procedure(wlB() mcpShot("hsc_flat")
  w2 = geOpen(?lib lib ?cell "hsc_core" ?view "schematic" ?mode "r")
  hiSetCurrentWindow(w2) hiResizeWindow(w2 list(0:0 1600:1000))
  hiRegTimer("wlC()" 30))
procedure(wlC() errset(evalstring(hiGetBindKey("Schematics" "<Key>f")) t) hiRegTimer("wlD()" 30))
procedure(wlD() mcpShot("hsc_core") printf("MCP:OK=1\n") exit(0))
hiRegTimer("wlA()" 40)
'''
log, got, _ = run_gui(il, shots=["hsc_flat", "hsc_core"], timeout=800, tag="hscf")
open("designs/hscasc/build_flat.log", "w", encoding="utf-8").write(log)
print(got)
conn = dict(re.findall(r"MCP:conn (\S+)=(\S+)", log))
nets = {}
for t, n in conn.items(): nets.setdefault(n, []).append(t)
print("FLAT NETS:")
for n, ts in sorted(nets.items()): print(" ", n, sorted(ts))
cconn = dict(re.findall(r"MCP:cconn (\S+)=(\S+)", log))
cnets = {}
for t, n in cconn.items(): cnets.setdefault(n, []).append(t)
print("CORE NETS:")
for n, ts in sorted(cnets.items()): print(" ", n, sorted(ts))
print(re.findall(r"MCP:flatcheck[^\n]*|MCP:corecheck[^\n]*", log))
